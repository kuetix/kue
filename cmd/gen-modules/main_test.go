func writeFile(t *testing.T, path, content string) {
	t.Helper()
	if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
		t.Fatal(err)
	}
}

func readFile(t *testing.T, path string) string {
	t.Helper()
	b, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	return string(b)
}

// assertGofmtClean parses+formats the Go source at path with go/format and
// fails if it isn't syntactically valid or isn't already gofmt-clean —
// generated Go that needs `gofmt -w` would fail CI's fmt-check.
func assertGofmtClean(t *testing.T, path string) {
	t.Helper()
	src := readFile(t, path)
	formatted, err := format.Source([]byte(src))
	if err != nil {
		t.Fatalf("generated Go is not valid: %v\n%s", err, src)
	}
	if string(formatted) != src {
		t.Errorf("generated Go is not gofmt-clean:\n%s", src)
	}
}
