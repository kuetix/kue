func TestModuleWired(t *testing.T) {
	cases := []struct {
		name string
		m    module
		want bool
	}{
		{"fully specified + enabled", module{Enabled: true, ImportPath: "x/y", Alias: "Y"}, true},
		{"disabled", module{Enabled: false, ImportPath: "x/y", Alias: "Y"}, false},
		{"bundled_via another module", module{Enabled: true, BundledVia: "cli", ImportPath: "x/y", Alias: "Y"}, false},
		{"missing import_path", module{Enabled: true, Alias: "Y"}, false},
		{"missing alias", module{Enabled: true, ImportPath: "x/y"}, false},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			if got := c.m.wired(); got != c.want {
				t.Errorf("wired() = %v, want %v", got, c.want)
			}
		})
	}
}

func TestLoadManifest(t *testing.T) {
	dir := t.TempDir()
	path := filepath.Join(dir, "modules.yaml")

	t.Run("valid", func(t *testing.T) {
		writeFile(t, path, `
modules:
  - name: cli
    go_module: github.com/kuetix/std-cli
    import_path: github.com/kuetix/std-cli/modules
    alias: StdCliModule
    enabled: true
    description: CLI stuff
`)
		mods, err := loadManifest(path)
		if err != nil {
			t.Fatalf("unexpected error: %v", err)
		}
		if len(mods) != 1 || mods[0].Name != "cli" {
			t.Fatalf("got %#v", mods)
		}
	})

	t.Run("missing file", func(t *testing.T) {
		if _, err := loadManifest(filepath.Join(dir, "nope.yaml")); err == nil {
			t.Fatal("expected an error for a missing file")
		}
	})

	t.Run("empty module list", func(t *testing.T) {
		writeFile(t, path, "modules: []\n")
		if _, err := loadManifest(path); err == nil {
			t.Fatal("expected an error for an empty module list")
		}
	})

	t.Run("malformed yaml", func(t *testing.T) {
		writeFile(t, path, "modules: [this is not: valid: yaml\n")
		if _, err := loadManifest(path); err == nil {
			t.Fatal("expected an error for malformed yaml")
		}
	})
}

func TestWriteModulesGo(t *testing.T) {
	mods := []module{
		{Name: "cli", ImportPath: "github.com/kuetix/std-cli/modules", Alias: "StdCliModule", Enabled: true, Note: "also pulls in std-core"},
		{Name: "core", BundledVia: "cli", Enabled: true}, // no import/Enable() of its own
		{Name: "auth", ImportPath: "github.com/kuetix/std-auth/modules", Alias: "StdAuthModule", Enabled: true},
		{Name: "disabled-one", ImportPath: "github.com/kuetix/std-x/modules", Alias: "StdXModule", Enabled: false},
	}

	dir := t.TempDir()
	path := filepath.Join(dir, "modules.go")
	if err := writeModulesGo(path, mods); err != nil {
		t.Fatalf("writeModulesGo: %v", err)
	}
	got := readFile(t, path)

	// Header marks the file as generated.
	if !strings.Contains(got, "Code generated by gen-modules") || !strings.Contains(got, "DO NOT EDIT") {
		t.Errorf("missing generated-file header:\n%s", got)
	}

	// Wired modules get an import + an Enable() call; core (bundled_via) and
	// the disabled module get neither.
	for _, want := range []string{
		`StdAuthModule "github.com/kuetix/std-auth/modules"`,
		`StdCliModule "github.com/kuetix/std-cli/modules"`,
		"StdCliModule.Enable() // also pulls in std-core",
		"StdAuthModule.Enable()",
	} {
		if !strings.Contains(got, want) {
			t.Errorf("expected to find %q in:\n%s", want, got)
		}
	}
	for _, unwanted := range []string{"StdXModule", "CoreModule", "core.Enable"} {
		if strings.Contains(got, unwanted) {
			t.Errorf("did not expect %q in:\n%s", unwanted, got)
		}
	}

	// Imports come out alphabetically by alias regardless of YAML order.
	authIdx := strings.Index(got, `StdAuthModule "`)
	cliIdx := strings.Index(got, `StdCliModule "`)
	if authIdx < 0 || cliIdx < 0 || authIdx > cliIdx {
		t.Errorf("expected StdAuthModule import before StdCliModule, got:\n%s", got)
	}

	// Enable() calls keep YAML order (cli before auth here), not import order.
	cliCallIdx := strings.Index(got, "StdCliModule.Enable()")
	authCallIdx := strings.Index(got, "StdAuthModule.Enable()")
	if cliCallIdx < 0 || authCallIdx < 0 || cliCallIdx > authCallIdx {
		t.Errorf("expected StdCliModule.Enable() before StdAuthModule.Enable(), got:\n%s", got)
	}
}

